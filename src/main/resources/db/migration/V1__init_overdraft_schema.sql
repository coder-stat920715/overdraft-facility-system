-- Overdraft Facility Management System: initial schema (PostgreSQL 12+ and H2 in PostgreSQL mode)

CREATE TABLE overdraft_account (
    id                            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_number                VARCHAR(32)   NOT NULL,
    customer_id                   VARCHAR(64)   NOT NULL,
    bank_name                     VARCHAR(20)   NOT NULL,
    sanctioned_limit              NUMERIC(19,4) NOT NULL,
    utilized_amount               NUMERIC(19,4) NOT NULL DEFAULT 0,
    available_limit               NUMERIC(19,4) NOT NULL,
    annual_interest_rate          NUMERIC(7,4)  NOT NULL,
    accumulated_unbilled_interest NUMERIC(19,4) NOT NULL DEFAULT 0,
    status                        VARCHAR(16)   NOT NULL,
    billing_cycle_day             INTEGER       NOT NULL DEFAULT 1,
    opened_at                     TIMESTAMP     NOT NULL,
    updated_at                    TIMESTAMP     NOT NULL,
    version                       BIGINT        NOT NULL DEFAULT 0,
    CONSTRAINT uq_od_account_number UNIQUE (account_number),
    CONSTRAINT ck_od_sanctioned_positive CHECK (sanctioned_limit > 0),
    CONSTRAINT ck_od_utilized_non_negative CHECK (utilized_amount >= 0),
    CONSTRAINT ck_od_unbilled_non_negative CHECK (accumulated_unbilled_interest >= 0),
    CONSTRAINT ck_od_rate_range CHECK (annual_interest_rate >= 0 AND annual_interest_rate <= 100),
    CONSTRAINT ck_od_cycle_day CHECK (billing_cycle_day BETWEEN 1 AND 28),
    CONSTRAINT ck_od_status CHECK (status IN ('ACTIVE', 'FROZEN', 'CLOSED'))
);

CREATE INDEX idx_od_account_customer ON overdraft_account (customer_id);
CREATE INDEX idx_od_account_status ON overdraft_account (status);

CREATE TABLE od_transaction (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id            BIGINT        NOT NULL,
    transaction_type      VARCHAR(24)   NOT NULL,
    amount                NUMERIC(19,4) NOT NULL,
    utilized_balance_after NUMERIC(19,4) NOT NULL,
    available_limit_after NUMERIC(19,4) NOT NULL,
    reference_id          VARCHAR(64),
    description           VARCHAR(255),
    created_at            TIMESTAMP     NOT NULL,
    CONSTRAINT fk_od_txn_account FOREIGN KEY (account_id) REFERENCES overdraft_account (id),
    CONSTRAINT ck_od_txn_type CHECK (transaction_type IN ('DRAWDOWN', 'REPAYMENT', 'INTEREST_CHARGED')),
    CONSTRAINT ck_od_txn_amount CHECK (amount > 0),
    CONSTRAINT uq_od_txn_reference UNIQUE (account_id, reference_id)
);

CREATE INDEX idx_od_txn_account_created ON od_transaction (account_id, created_at);

CREATE TABLE daily_interest_ledger (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id       BIGINT        NOT NULL,
    accrual_date     DATE          NOT NULL,
    utilized_balance NUMERIC(19,4) NOT NULL,
    interest_rate    NUMERIC(7,4)  NOT NULL,
    accrued_amount   NUMERIC(19,4) NOT NULL,
    billed           BOOLEAN       NOT NULL DEFAULT FALSE,
    created_at       TIMESTAMP     NOT NULL,
    CONSTRAINT fk_od_ledger_account FOREIGN KEY (account_id) REFERENCES overdraft_account (id),
    CONSTRAINT uq_od_ledger_account_date UNIQUE (account_id, accrual_date),
    CONSTRAINT ck_od_ledger_accrued CHECK (accrued_amount >= 0)
);

CREATE INDEX idx_od_ledger_billing ON daily_interest_ledger (billed, accrual_date);
